package com.codereview.agent.triage.screen;

import com.codereview.agent.triage.diff.FileChange;

import java.util.List;
import java.util.Locale;

/**
 * Drops files that no reviewer would look at, before any parsing or model call happens.
 *
 * <p>Screening is deliberately conservative: everything it removes is counted and reported,
 * and an explicit include list can pull a path back in. A file silently disappearing from a
 * review is worse than reviewing one file too many.
 */
public final class Screening {

    /** First lines of a file that claim it was produced by a generator. */
    private static final List<String> GENERATED_MARKERS = List.of(
            "@generated", "@javax.annotation.processing.Generated",
            "do not edit", "code generated by", "auto-generated", "autogenerated");

    private static final List<String> GENERATED_PATH_MARKERS = List.of(
            "/generated/", "/gen/", "/build/generated/", "/target/generated-sources/");

    public record Decision(boolean review, String reason) {

        static Decision keep() {
            return new Decision(true, "");
        }

        static Decision skip(String reason) {
            return new Decision(false, reason);
        }
    }

    private final List<String> includePaths;

    public Screening() {
        this(List.of());
    }

    public Screening(List<String> includePaths) {
        this.includePaths = List.copyOf(includePaths);
    }

    public Decision screen(FileChange change) {
        String path = change.displayPath();
        if (path == null) {
            return Decision.skip("no path");
        }
        if (includePaths.stream().anyMatch(path::startsWith)) {
            return Decision.keep();
        }
        if (!change.isJavaSource()) {
            return Decision.skip("not java source");
        }
        if (change.oldText() == null && change.newText() == null) {
            return Decision.skip("binary or oversized content");
        }
        String lowerPath = path.toLowerCase(Locale.ROOT);
        for (String marker : GENERATED_PATH_MARKERS) {
            if (lowerPath.contains(marker)) {
                return Decision.skip("generated path");
            }
        }
        if (looksGenerated(change.newText()) || looksGenerated(change.oldText())) {
            return Decision.skip("generated file marker");
        }
        if (change.edits().isEmpty()) {
            return Decision.skip("no line changes");
        }
        return Decision.keep();
    }

    private static boolean looksGenerated(String text) {
        if (text == null) {
            return false;
        }
        String head = text.length() > 2000 ? text.substring(0, 2000) : text;
        String lowerHead = head.toLowerCase(Locale.ROOT);
        for (String marker : GENERATED_MARKERS) {
            if (lowerHead.contains(marker)) {
                return true;
            }
        }
        return false;
    }
}
